function hashSeed(seed: string): number {
  let hash = 0;

  for (let index = 0; index < seed.length; index += 1) {
    hash = (hash * 31 + seed.charCodeAt(index)) >>> 0;
  }

  return hash;
}

/**
 * Generates a stable name from a deterministic seed so starter NPC names
 * remain persistent after they have been written into plot detail.
 */
export function makeNpcName(seed: string): string {
  const hash = hashSeed(seed);
  const firstName = FIRST_NAMES[hash % FIRST_NAMES.length];
  const descriptor =
    DESCRIPTORS[Math.floor(hash / FIRST_NAMES.length) % DESCRIPTORS.length];

  return `${firstName} ${descriptor}`;
}